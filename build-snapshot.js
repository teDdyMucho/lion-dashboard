// Downloads every tab of both Google Sheets and writes the offline fallbacks the
// dashboard uses when it can't reach Google Sheets:
//   snapshot.js       -> window.LION_SNAPSHOT       (backlog workbook)
//   snapshot-perf.js  -> window.LION_PERF_SNAPSHOT  (technician performance workbook)
// Usage: node build-snapshot.js
const fs = require('fs');
const path = require('path');
const P = require('./parser.js');
const PP = require('./perf-parser.js');

async function fetchTabs(api) {
  const texts = {};
  for (const tab of api.TABS) {
    const res = await fetch(api.csvUrl(tab));
    if (!res.ok) { if ((api.OPTIONAL_TABS || []).includes(tab)) { console.warn(tab + ': HTTP ' + res.status + ' (optional, skipped)'); continue; } throw new Error(tab + ': HTTP ' + res.status); }
    texts[tab] = await res.text();
  }
  return texts;
}

(async () => {
  const model = P.buildModel(await fetchTabs(P));
  model.snapshotAt = new Date().toISOString();
  fs.writeFileSync(path.join(__dirname, 'snapshot.js'),
    '// Generated by build-snapshot.js - do not edit by hand.\nwindow.LION_SNAPSHOT = ' + JSON.stringify(model) + ';\n');
  for (const z of model.zones) {
    console.log(z.id.padEnd(7), 'master WOs', String(z.openWos).padStart(4), '| parsed WOs', String(z.wos.length).padStart(4),
      '| LVL sum', z.wos.reduce((s, w) => s + w.lvl, 0), 'vs', z.totalLvl, '| waiting', z.waiting, '| export', z.exportDate);
  }
  console.log('Waiting WOs:', model.waiting.length, '| LVL guide rows:', model.assessment.length);

  const perf = PP.buildModel(await fetchTabs(PP));
  perf.snapshotAt = model.snapshotAt;
  fs.writeFileSync(path.join(__dirname, 'snapshot-perf.js'),
    '// Generated by build-snapshot.js - do not edit by hand.\nwindow.LION_PERF_SNAPSHOT = ' + JSON.stringify(perf) + ';\n');
  const t = perf.perf.team || {};
  console.log('Performance:', perf.perf.daily.length, 'team days,', perf.perf.techs.length, 'techs, team', t.comp + '/' + t.sched,
    '| rolling', perf.rolling.daily.length, 'days | input log', perf.inputLog.length, 'rows | zone-daily', perf.zoneDaily.list.length,
    'rows');
})().catch(e => { console.error(e); process.exit(1); });
